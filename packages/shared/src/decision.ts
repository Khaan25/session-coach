import { z } from "zod";

/**
 * The Decision object: the contract between the pipeline (writes `decision_cards`)
 * and the review loop (reads them). Change it only after agreeing in the team channel.
 */

/** One quote backing a decision, checked by plain code after extraction. */
export const evidenceSchema = z.object({
  /** Position of the event in the filtered timeline (E1, E2, ...), not the raw JSONL line. */
  event_index: z.number().int().positive(),
  /** Copied word for word from that event. */
  quote: z.string().min(1),
  /** File the event touched, when it is a file change. */
  file: z.string().nullable(),
  /** Inclusive line range in `file`, when the event is a file change. */
  lines: z
    .tuple([z.number().int().positive(), z.number().int().positive()])
    .refine(([start, end]) => start <= end, "start line must not exceed end line")
    .nullable(),
  /** True when the quote exists in the cited event after normalising whitespace. */
  verified: z.boolean(),
});

/**
 * stated: the agent or user gave the reason (agent text, a prompt, or a DECISIONS.md write).
 * inferred: the model guessed the reason, and the card says so.
 */
export const decisionSourceSchema = z.enum(["stated", "inferred"]);

/**
 * One decision the agent made in a session, turned into a card the learner must explain back.
 * The refine keeps `flagged` and `hidden` honest, mirroring the generated columns in Postgres.
 */
export const decisionCardSchema = z
  .object({
    id: z.uuid(),
    session_id: z.uuid(),
    user_id: z.uuid(),
    /** Order on screen, 0-based. */
    position: z.number().int().min(0),
    /** What was decided, in one sentence. */
    decision: z.string().min(1),
    /** The reason, stated or inferred per `source`. */
    why: z.string().min(1),
    source: decisionSourceSchema,
    evidence: z.array(evidenceSchema).min(1),
    /** Files the decision changed, for context on the card. */
    files: z.array(z.string()),
    /** What the learner is asked to explain. */
    question: z.string().min(1),
    /** The answer key used to grade the learner. Never sent to the browser before they answer. */
    model_answer: z.string().min(1),
    /** True when any evidence item has `verified: false`. Shown as a small label. Generated by the database. */
    flagged: z.boolean(),
    /** True when no evidence item is verified. Kept for the accuracy check, never shown to learners. Generated by the database. */
    hidden: z.boolean(),
    created_at: z.iso.datetime({ offset: true }),
  })
  .refine(
    (card) => {
      const flags = getEvidenceFlags(card.evidence);
      return card.flagged === flags.flagged && card.hidden === flags.hidden;
    },
    { message: "flagged and hidden must match getEvidenceFlags(evidence)", path: ["flagged"] },
  );

export type Evidence = z.infer<typeof evidenceSchema>;
export type DecisionSource = z.infer<typeof decisionSourceSchema>;
export type DecisionCard = z.infer<typeof decisionCardSchema>;

/**
 * Derives `flagged` and `hidden` from the evidence check, so both sides compute them the same way.
 *
 * @param evidence - The card's evidence; only `verified` is read.
 * @returns `flagged`: at least one quote failed the check. `hidden`: none passed.
 */
export function getEvidenceFlags(evidence: readonly Pick<Evidence, "verified">[]) {
  const verifiedCount = evidence.filter(({ verified }) => verified).length;
  return {
    flagged: verifiedCount < evidence.length,
    hidden: verifiedCount === 0,
  };
}
